// Builds the one-file version of aspire-probe for pasting into the Supabase dashboard editor.
// Source of truth stays supabase/functions/aspire-probe/{index,probe}.ts. Run: npm run bundle:probe
import { readFileSync, writeFileSync } from 'node:fs';

export function bundle() {
  const dir = new URL('../supabase/functions/aspire-probe/', import.meta.url);
  const probe = readFileSync(new URL('probe.ts', dir), 'utf8');
  const index = readFileSync(new URL('index.ts', dir), 'utf8').replace(/^import \{ probe, BASE \} from '\.\/probe\.ts';\n/m, '');
  const imports = index.match(/^import .*$/gm).join('\n');
  const body = index.replace(/^import .*\n/gm, '');
  return `// GENERATED by scripts/bundle-probe.mjs from supabase/functions/aspire-probe. Do not edit by hand.
// Paste this whole file into the Supabase dashboard editor as the function "aspire-probe".
${imports}

// ======================= probe.ts =======================
${probe.trim()}

// ======================= index.ts =======================
${body.trim()}
`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  writeFileSync(new URL('../supabase/dashboard/aspire-probe.ts', import.meta.url), bundle());
  console.log('wrote supabase/dashboard/aspire-probe.ts');
}
