// Builds the one-file versions of the edge functions for pasting into the Supabase dashboard editor.
// Source of truth stays supabase/functions/<name>/*.ts. Run: npm run bundle:probe
import { readFileSync, writeFileSync } from 'node:fs';

const LOCAL = /^import .* from '\.\.?\/[\w/-]+\.ts';\n/gm;
const ANY_IMPORT = /^import .*$/gm;

// in dependency order. a path outside the function's own folder is shared source.
export const FUNCTIONS = {
  'aspire-probe': ['client.ts', 'probe.ts', 'probe2.ts', 'probe3.ts', 'gate.ts', 'index.ts'],
  'aspire-sync': ['../aspire-probe/gate.ts', 'aspire.ts', 'sync.ts', 'index.ts'],
};

export function bundle(name = 'aspire-probe') {
  const dir = new URL(`../supabase/functions/${name}/`, import.meta.url);
  const read = (f) => readFileSync(new URL(f, dir), 'utf8');
  const files = FUNCTIONS[name].map((f) => [f, read(f).replace(LOCAL, '')]);
  const imports = [...new Set(files.flatMap(([, s]) => s.match(ANY_IMPORT) || []))].join('\n');
  const body = files.map(([f, s]) => `// ======================= ${f.split('/').pop()} =======================\n${s.replace(ANY_IMPORT, '').trim()}`).join('\n\n');
  return `// GENERATED by scripts/bundle-probe.mjs from supabase/functions/${name}. Do not edit by hand.
// Paste this whole file into the Supabase dashboard editor as the function "${name}".
${imports ? imports + '\n' : ''}
${body}
`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  for (const name of Object.keys(FUNCTIONS)) {
    writeFileSync(new URL(`../supabase/dashboard/${name}.ts`, import.meta.url), bundle(name));
    console.log(`wrote supabase/dashboard/${name}.ts`);
  }
}
